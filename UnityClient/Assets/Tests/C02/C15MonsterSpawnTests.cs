#if UNITY_EDITOR
using System;
using System.Globalization;
using System.IO;
using System.Reflection;
using System.Text;
using NUnit.Framework;
using UnityEngine;

namespace C02.Tests
{
    public sealed class C15MonsterSpawnTests
    {
        [Test]
        [Category("SpawnExport")]
        public void DefaultCandidateExportsDeterministicUtf8LayoutConstants()
        {
            var content = ScriptableObject.CreateInstance<C15MonsterSpawns>();
            string directory = Path.Combine(Path.GetTempPath(), "C15SpawnExport-" + Guid.NewGuid().ToString("N"));
            CultureInfo originalCulture = CultureInfo.CurrentCulture;
            try
            {
                CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo("fr-FR");
                Export(content, directory);
                byte[] first = File.ReadAllBytes(Path.Combine(directory, "MonsterSpawns.inc"));
                const string expected = "// Generated by C15MonsterSpawnExport. Do not edit.\n" +
                    "namespace Data {\n" +
                    "inline constexpr int REGULAR_MONSTERS_PER_CELL = 8;\n" +
                    "inline constexpr int STRONG_MONSTERS_PER_CELL = 2;\n" +
                    "inline constexpr int MONSTER_SPAWN_EDGE_INSET = 1;\n" +
                    "}\n";
                Assert.That(first, Is.EqualTo(new UTF8Encoding(false).GetBytes(expected)));
                CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo("ar-SA");
                Export(content, directory);
                Assert.That(File.ReadAllBytes(Path.Combine(directory, "MonsterSpawns.inc")), Is.EqualTo(first));
                Assert.That(Directory.GetFiles(directory).Length, Is.EqualTo(1));
            }
            finally
            {
                UnityEngine.Object.DestroyImmediate(content);
                CultureInfo.CurrentCulture = originalCulture;
                if (Directory.Exists(directory)) Directory.Delete(directory, true);
            }
        }

        [Test]
        [Category("SpawnExport")]
        public void InvalidCountOrInsetPreservesExistingOutput()
        {
            var content = ScriptableObject.CreateInstance<C15MonsterSpawns>();
            string directory = Path.Combine(Path.GetTempPath(), "C15SpawnExport-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(directory);
            string outputPath = Path.Combine(directory, "MonsterSpawns.inc");
            byte[] sentinel = { 17, 29, 41 };
            File.WriteAllBytes(outputPath, sentinel);
            try
            {
                Action assertPreserved = () =>
                {
                    var failure = Assert.Throws<TargetInvocationException>(() => Export(content, directory));
                    Assert.That(failure.InnerException, Is.TypeOf<InvalidOperationException>());
                    Assert.That(File.ReadAllBytes(outputPath), Is.EqualTo(sentinel));
                    Assert.That(Directory.GetFiles(directory).Length, Is.EqualTo(1));
                };
                content.regularPerCell = -1;
                assertPreserved();
                content.regularPerCell = 8;
                content.strongPerCell = 42;
                assertPreserved();
                content.strongPerCell = 2;
                content.edgeInset = 0;
                assertPreserved();
                content.edgeInset = 22;
                assertPreserved();
            }
            finally
            {
                UnityEngine.Object.DestroyImmediate(content);
                Directory.Delete(directory, true);
            }
        }

        private static void Export(C15MonsterSpawns content, string directory)
        {
            var exporter = Type.GetType("C02.Editor.C15MonsterSpawnExport, C02.Editor", true);
            exporter.GetMethod("ExportValidated", new[] { typeof(C15MonsterSpawns), typeof(string) })
                .Invoke(null, new object[] { content, directory });
        }
    }
}
#endif
