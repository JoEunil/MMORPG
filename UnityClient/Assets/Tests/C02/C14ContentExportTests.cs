        [Test]
        [Category("ContentExport")]
        public void DefaultContentExportsExactUtf8InitializersDeterministically()
        {
            var content = ScriptableObject.CreateInstance<C14ServerContent>();
            string directory = Path.Combine(Path.GetTempPath(), "C14ContentExport-" + Guid.NewGuid().ToString("N"));
            var originalCulture = CultureInfo.CurrentCulture;
            try
            {
                CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo("fr-FR");
                Export(content, directory);
                var ring = File.ReadAllBytes(Path.Combine(directory, "PlayerRing.inc"));
                var monster = File.ReadAllBytes(Path.Combine(directory, "Monster0.inc"));
                const string expectedRing = "// Generated by C14ServerContentExport. Do not edit.\n" +
                    "SkillData{\n    1, 2,\n    20, 120,\n    {\n" +
                    "        SkillPhase{ 0, 0, {SkillRangeType::None, 0.0f, 0.0f}, 0 },\n" +
                    "        SkillPhase{ 16, 1, {SkillRangeType::Circle, 8.0f, 0.0f}, 100 },\n    }\n},\n";
                const string expectedMonster = "// Generated by C14ServerContentExport. Do not edit.\n" +
                    "{\n    0,\n    1500,\n    5,\n    300,\n    1.0f,\n    {\n" +
                    "        { 1.0f, 0, 2,\n            {\n" +
                    "                { 0, 20 },\n                { 0, 20 },\n" +
                    "            }\n        },\n    },\n    {10}\n},\n";
                Assert.That(ring, Is.EqualTo(new UTF8Encoding(false).GetBytes(expectedRing)));
                Assert.That(monster, Is.EqualTo(new UTF8Encoding(false).GetBytes(expectedMonster)));

                CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo("ar-SA");
                Export(content, directory);
                Assert.That(File.ReadAllBytes(Path.Combine(directory, "PlayerRing.inc")), Is.EqualTo(ring));
                Assert.That(File.ReadAllBytes(Path.Combine(directory, "Monster0.inc")), Is.EqualTo(monster));
                Assert.That(Directory.GetFiles(directory).Length, Is.EqualTo(2));
            }
            finally
            {
                CultureInfo.CurrentCulture = originalCulture;
                UnityEngine.Object.DestroyImmediate(content);
                if (Directory.Exists(directory)) Directory.Delete(directory, true);
            }
        }

        [Test]
        [Category("ContentExport")]
        public void InvalidCandidateIdsCountsAndValuesLeaveBothOutputsUntouched()
        {
            var content = ScriptableObject.CreateInstance<C14ServerContent>();
            string directory = Path.Combine(Path.GetTempPath(), "C14ContentExport-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(directory);
            var ringBefore = new byte[] { 10, 20, 30 };
            var monsterBefore = new byte[] { 40, 50, 60 };
            File.WriteAllBytes(Path.Combine(directory, "PlayerRing.inc"), ringBefore);
            File.WriteAllBytes(Path.Combine(directory, "Monster0.inc"), monsterBefore);
            try
            {
                Action assertPreserved = () =>
                {
                    var failure = Assert.Throws<TargetInvocationException>(() => Export(content, directory));
                    Assert.That(failure.InnerException, Is.TypeOf<InvalidOperationException>());
                    Assert.That(File.ReadAllBytes(Path.Combine(directory, "PlayerRing.inc")), Is.EqualTo(ringBefore));
                    Assert.That(File.ReadAllBytes(Path.Combine(directory, "Monster0.inc")), Is.EqualTo(monsterBefore));
                    Assert.That(Directory.GetFiles(directory).Length, Is.EqualTo(2));
                };

                content.ring.skillID = 2;
                assertPreserved();
                content.ring.skillID = 1;
                content.monster0.id = 1;
                assertPreserved();
                content.monster0.id = 0;
                var ringPhases = content.ring.phases;
                content.ring.phases = Array.Empty<C14ServerContent.SkillPhase>();
                assertPreserved();
                content.ring.phases = ringPhases;
                var steps = content.monster0.phases[0].steps;
                content.monster0.phases[0].steps = new C14ServerContent.SkillStep[3];
                assertPreserved();
                content.monster0.phases[0].steps = steps;
                var monsterPhases = content.monster0.phases;
                content.monster0.phases = new C14ServerContent.MonsterPhase[9];
                assertPreserved();
                content.monster0.phases = monsterPhases;
                content.ring.flags = 4;
                assertPreserved();
                content.ring.flags = 2;
                content.ring.phases[1].range = (C14SkillRange)255;
                assertPreserved();
                content.ring.phases[1].range = C14SkillRange.Circle;
                content.ring.phases[1].range1 = float.NaN;
                assertPreserved();
                content.ring.phases[1].range1 = 8;
                content.monster0.moveSpeed = float.PositiveInfinity;
                assertPreserved();
                content.monster0.moveSpeed = 1;
                content.monster0.maxHp = 2147483648u;
                assertPreserved();
                content.monster0.maxHp = 1500;
                content.monster0.phases[0].steps[0].skillID = 5;
                assertPreserved();
                content.monster0.phases[0].steps[0].skillID = 0;
                content.monster0.phases = new[] { monsterPhases[0], new C14ServerContent.MonsterPhase() };
                assertPreserved();
                content.monster0.phases = monsterPhases;
                content.monster0.respawnTicks = 0;
                assertPreserved();
                content.monster0.respawnTicks = 300;
                content.monster0.phases = new[]
                {
                    new C14ServerContent.MonsterPhase { hpThreshold = 0.0001f },
                    new C14ServerContent.MonsterPhase { hpThreshold = 0.00001f }
                };
                assertPreserved(); // First absolute threshold truncates to zero.
                content.monster0.phases[0].hpThreshold = 0.001f;
                assertPreserved(); // Absolute one cannot be crossed while HP is positive.
                content.monster0.phases[0].hpThreshold = 1;
                Assert.DoesNotThrow(() => Export(content, directory)); // The final threshold is not a transition gate.
            }
            finally
            {
                UnityEngine.Object.DestroyImmediate(content);
                Directory.Delete(directory, true);
            }
        }

        private static void Export(C14ServerContent content, string directory)
        {
            var exporter = Type.GetType("C02.Editor.C14ServerContentExport, C02.Editor", true);
            exporter.GetMethod("ExportValidated", new[] { typeof(C14ServerContent), typeof(string) })
                .Invoke(null, new object[] { content, directory });
        }
    }
